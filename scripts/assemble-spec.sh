#!/usr/bin/env bash
# Builds openapi/openapi.yaml from the backend's hand-written contract fragment.
# Used only while the live spec is unpublished; see scripts/update-spec.sh.
# Usage: scripts/assemble-spec.sh <path-to-openapi-extensions.yaml> [source-label]
set -euo pipefail
fragment="$1"
label="${2:-$fragment}"
root="$(cd "$(dirname "$0")/.." && pwd)"
{
  echo "# GENERATED by scripts/assemble-spec.sh from: $label"
  echo "# Do not edit by hand. Replace with the live spec via 'make update-spec'."
  cat "$root/openapi/header.yaml"
  sed -e 's#\${authBase}#https://auth.kof22.com#g' -e '/^#/d' "$fragment"
} > "$root/openapi/openapi.yaml"
echo "wrote openapi/openapi.yaml"
